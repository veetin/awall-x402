/**
 * Prepare the Stellar testnet accounts the demo needs.
 *
 * Creates or reuses the paying account, funds it with friendbot, adds the USDC
 * trustline and reports XLM, USDC and the trustline. The receiving account gets
 * the same treatment when `STELLAR_PAY_TO_SECRET` is set.
 *
 * A generated secret key is written to `.env` and never printed.
 */
import { appendFileSync, existsSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { Keypair } from "@stellar/stellar-sdk";
import {
  DEFAULT_FRIENDBOT_URL,
  DEFAULT_HORIZON_URL,
  STELLAR_TESTNET_USDC,
  STELLAR_TESTNET_USDC_ISSUER,
  USDC_FAUCET_URL,
} from "../src/config.js";
import { createHorizonTestnet } from "../src/horizon.js";
import { isZero, prepareAccount, type AccountReport } from "../src/testnet.js";

const ENV_FILE = fileURLToPath(new URL("../.env", import.meta.url));

/**
 * Resolve the paying account's secret key, generating one when there is none.
 *
 * @param log - Where to write progress.
 * @returns The secret key and whether this run generated it.
 */
function resolvePayerSecret(log: (line: string) => void): {
  secret: string;
  generated: boolean;
} {
  const fromEnv = process.env["STELLAR_SECRET"];
  if (fromEnv) return { secret: fromEnv, generated: false };

  if (existsSync(ENV_FILE) && readFileSync(ENV_FILE, "utf8").includes("STELLAR_SECRET=")) {
    throw new Error(
      `${ENV_FILE} already holds STELLAR_SECRET but it is not in the environment. ` +
        `Run this through "pnpm --filter @awall/agent-m2m setup:testnet", which loads it.`,
    );
  }

  const keypair = Keypair.random();
  appendFileSync(
    ENV_FILE,
    `${existsSync(ENV_FILE) ? "\n" : ""}# Stellar testnet hot wallet, generated by setup:testnet\nSTELLAR_SECRET=${keypair.secret()}\n`,
    { mode: 0o600 },
  );
  log(`generated a new testnet keypair; its secret key went to ${ENV_FILE}`);
  return { secret: keypair.secret(), generated: true };
}

/**
 * Print one account's state.
 *
 * @param report - What the preparation found.
 * @param log - Where to write.
 */
function printReport(report: AccountReport, log: (line: string) => void): void {
  log("");
  log(`${report.label}`);
  log(`  address    ${report.address}`);
  log(`  XLM        ${report.xlm}${report.created ? "  (funded by friendbot now)" : ""}`);
  log(`  USDC       ${report.usdc}`);
  log(
    `  trustline  ${report.hasTrustline ? "yes" : "no"}` +
      `${report.trustlineAdded ? "  (added now)" : ""}`,
  );
}

/**
 * Run the setup.
 *
 * @returns The process exit code.
 */
async function main(): Promise<number> {
  const log = (line: string): void => {
    process.stdout.write(`${line}\n`);
  };

  const network = createHorizonTestnet({
    horizonUrl: process.env["STELLAR_HORIZON_URL"] ?? DEFAULT_HORIZON_URL,
    friendbotUrl: process.env["STELLAR_FRIENDBOT_URL"] ?? DEFAULT_FRIENDBOT_URL,
    usdcIssuer: STELLAR_TESTNET_USDC_ISSUER,
  });

  log(`network    stellar:testnet`);
  log(`USDC SAC   ${STELLAR_TESTNET_USDC}`);
  log(`USDC issuer ${STELLAR_TESTNET_USDC_ISSUER}`);

  const payer = resolvePayerSecret(log);
  const reports: AccountReport[] = [
    await prepareAccount(network, {
      label: "payer (the agent)",
      address: Keypair.fromSecret(payer.secret).publicKey(),
      secret: payer.secret,
      issuer: STELLAR_TESTNET_USDC_ISSUER,
    }),
  ];

  const payeeSecret = process.env["STELLAR_PAY_TO_SECRET"];
  if (payeeSecret) {
    reports.push(
      await prepareAccount(network, {
        label: "payee (the gateway's STELLAR_PAY_TO)",
        address: Keypair.fromSecret(payeeSecret).publicKey(),
        secret: payeeSecret,
        issuer: STELLAR_TESTNET_USDC_ISSUER,
      }),
    );
  }

  for (const report of reports) printReport(report, log);

  if (!payeeSecret) {
    log("");
    log("STELLAR_PAY_TO_SECRET is not set, so the receiving account was not touched.");
    log("The payee needs the same trustline, or settlement fails on the gateway side.");
  }

  // Only the payer spends USDC; the payee just needs somewhere to receive it.
  const payerReport = reports[0];
  if (payerReport !== undefined && isZero(payerReport.usdc)) {
    log("");
    log("The agent has no testnet USDC yet. To get some:");
    log(`  1. open ${USDC_FAUCET_URL}`);
    log("  2. pick the Stellar Testnet network and the USDC token");
    log(`  3. paste the agent address: ${payerReport.address}`);
    log("  4. the faucet sends 20 USDC per address every 2 hours");
    log("The trustline above must already exist, otherwise the faucet payment bounces.");
  }

  const missingTrustline = reports.filter(report => !report.hasTrustline);
  if (missingTrustline.length > 0) {
    log("");
    for (const report of missingTrustline) {
      log(`no USDC trustline on ${report.address} (${report.label})`);
    }
    return 1;
  }

  return 0;
}

main()
  .then(code => {
    process.exitCode = code;
  })
  .catch((error: unknown) => {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
    process.exitCode = 1;
  });
